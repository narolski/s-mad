def N(s):
    """LaTeX text-mode number with a typographic minus."""
    return s.replace("-", "$-$", 1) if s.startswith("-") else s


def strip_tail(s):
    return s[: -len("\n\\addlinespace")] if s.endswith("\n\\addlinespace") else s


def write(name, body):
    with open(os.path.join(TAB, name), "w") as f:
        f.write("% generated by smad-next src/supplement_v2/make_tables.py; do not edit by hand\n" + body)


def rng(table, specs, digits, sep="--"):
    lo, hi = R.v(table, ["min", specs], digits), R.v(table, ["max", specs], digits)
    return N(lo) if lo == hi else f"{N(lo)}{sep}{N(hi)}"


def jp(path, *keys, scale=1.0):
    return ["json", path, list(keys), scale]


