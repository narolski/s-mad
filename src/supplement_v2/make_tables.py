def batchc_spec(outcome, pair, what):
    """outcome: 'whole' (D-stratified, development + 80 screened test hosts) or 'splice' (unstratified, 80 screened test hosts)."""
    key = "R4_vs_R3_opencv|dev+clean80" if outcome == "whole" else "S4_vs_S3|clean80"
    g = "gain" if outcome == "whole" else "unstrat_gain"
    if what in CB_SEEDS:
        return jp(BATCHC, "contrasts", key, pair, g, what)
    if what == "mean":
        return jp(BATCHC, "contrasts", key, pair, "seed_mean" if outcome == "whole" else "unstrat_seed_mean")
    if what in ("lo", "hi"):
        return jp(BATCHC, "contrasts", key, pair, "ci", 0 if what == "lo" else 1)
    if what == "npos":
        return jp(BATCHC, "contrasts", key, pair, "n_positive")


def batchc_auc(outcome, arm, seed):
    key = "R4_vs_R3_opencv|dev+clean80" if outcome == "whole" else "S4_vs_S3|clean80"
    return jp(BATCHC, "contrasts", key, "per_seed", f"{arm}_s{seed}", "strat" if outcome == "whole" else "unstrat")


