"""Mirror-asymmetry test (AS0): markdown tables from the analysis CSVs (for result.md and the README).
  python3 -I as0_tables.py [--dir experiments/AS0_mirror-asymmetry] -> <dir>/tables.md"""
import argparse
import csv
import json
import pathlib

ap = argparse.ArgumentParser()
ap.add_argument("--dir", default="/home/narolski/smad-next/experiments/AS0_mirror-asymmetry")
a = ap.parse_args()
R = pathlib.Path(a.dir)
rows = list(csv.DictReader(open(R / "contrasts.csv")))
B5 = ["B1", "B2", "B3", "B4", "B5", "BB", "shape"]


def f(r):
    return f"{float(r['auc']):.3f} [{float(r['lo']):.3f}, {float(r['hi']):.3f}]"


def table(fam, subset=None, ch="Y", flip="F0", bands=B5, contrasts=None, title=""):
    sel = [r for r in rows if r["family"] == fam and (subset is None or r["subset"] == subset)]
    names = contrasts or list(dict.fromkeys(r["contrast"] for r in sel))
    out = [f"\n**{title}**\n", "| Contrast | subset | n X / n Y | " + " | ".join(bands) + " |",
           "|---|---|---|" + "---|" * len(bands)]
    for nm in names:
        subs = list(dict.fromkeys(r["subset"] for r in sel if r["contrast"] == nm))
        for sb in subs:
            cells, nn = [], ""
            for b in bands:
                if b == "shape":
                    m = [r for r in sel if r["contrast"] == nm and r["subset"] == sb and r["band"] == "shape"]
                else:
                    m = [r for r in sel if r["contrast"] == nm and r["subset"] == sb and r["band"] == b and
                         r["channel"] == ch and r["flip"] == flip]
                cells.append(f(m[0]) if m else "")
                if m and not nn:
                    nn = f"{m[0]['nX']} / {m[0]['nY']}"
            out.append(f"| {nm} | {sb} | {nn} | " + " | ".join(cells) + " |")
    return "\n".join(out)


md = ["# Mirror-asymmetry test (AS0): tables (generated by src/AS0/as0_tables.py)",
      "AUC = P(L(X) < L(Y)) with 95% person-bootstrap interval; L = ln(E_A/E_S); Y channel, flip F0 unless stated; "
      "BB = bands B1..B5 summed; shape = landmark-shape asymmetry."]
md.append(table("L", "pooled", title="Landmark ladder (AR1), both engines pooled"))
md.append(table("L", "opencv", title="Landmark ladder, OpenCV"))
md.append(table("L", "facemorpher", title="Landmark ladder, FaceMorpher"))
for ch in ("R", "G", "B", "RGB"):
    md.append(table("L", "pooled", ch=ch, contrasts=["K1 R4 vs R3"], bands=B5[:-1], title=f"K1, channel {ch}"))
md.append(table("L", "pooled", flip="F1", contrasts=["K1 R4 vs R3"], bands=B5[:-1], title="K1, landmark-midline flip F1"))
md.append(table("L-confound", None, title="K1 under confound controls (Y, F0)", bands=B5[:-1]))
md.append(table("R8", None, title="Same-session and cross-session same-person landmark morphs (R8)"))
md.append(table("G", "all", title="GAN latent blocks (Y, F0)"))
md.append(table("G", "all", flip="F1", title="GAN latent blocks (Y, F1)", bands=B5[:-1]))
md.append(table("D", "all", title="Diffusion-autoencoder ladder, DiffAE-native 256 (Y, F0)"))
md.append(table("Ds", "all", flip="F1", title="A43 stored crops (Y, F1)"))
md.append(table("X", "all", title="expanded123 DiffAE blocks (Y, F0)"))
h = list(csv.DictReader(open(R / "history.csv")))
md += ["\n**Storage-history shifts d = mean(L copy - L native) / SD(L native), Y, F0 (x = band below the cut-off)**\n",
       "| set | copy | n | scale | " + " | ".join(["B1", "B2", "B3", "B4", "B5", "BB"]) + " |", "|---|---|---|---|" + "---|" * 6]
for key in dict.fromkeys((r["set"], r["copy"]) for r in h):
    cells = []
    n = sc = ""
    for b in ["B1", "B2", "B3", "B4", "B5", "BB"]:
        m = [r for r in h if (r["set"], r["copy"]) == key and r["band"] == b and r["channel"] == "Y" and r["flip"] == "F0"]
        if m:
            r = m[0]
            cells.append(f"{float(r['d']):+.3f} [{float(r['lo']):+.3f}, {float(r['hi']):+.3f}]" + (" x" if r["below_cutoff"] == "1" else ""))
            n, sc = r["n"], r["scale"]
        else:
            cells.append("")
    md.append(f"| {key[0]} | {key[1]} | {n} | {sc} | " + " | ".join(cells) + " |")
d = list(csv.DictReader(open(R / "dose.csv")))
md += ["\n**Dose curve (graded FaceMorpher, paired dL = L(m) - L(0); predicted ln(m^2 + (1-m)^2))**\n",
       "| band | n | beta [CI] | reading | dL m=.1 / .2 / .3 / .4 / .5 (pred -0.198 / -0.386 / -0.545 / -0.654 / -0.693) | AUC vs m=0 at .1 ... .5 |",
       "|---|---|---|---|---|---|"]
for r in d:
    md.append(f"| {r['band']} | {r['n_hosts']} | {float(r['beta']):.3f} [{float(r['lo']):.3f}, {float(r['hi']):.3f}] | {r['reading']} | "
              + " / ".join(f"{float(r[f'med_dL_m{m:02d}']):+.3f}" for m in (10, 20, 30, 40, 50)) + " | "
              + " / ".join(f"{float(r[f'auc_m{m:02d}_vs_m00']):.3f}" for m in (10, 20, 30, 40, 50)) + " |")
s = list(csv.DictReader(open(R / "shares.csv")))
md += ["\n**Paired ratios per host (median exp(L_rung - L_R2w)) and person-specific share pi = 2 x R3 ratio - 1**\n",
       "| subset | band | n | R3/R2w [CI] | pi [CI] | R4/R2w [CI] (pred 0.5) | R3m/R2w [CI] |", "|---|---|---|---|---|---|---|"]
for r in s:
    md.append(f"| {r['subset']} | {r['band']} | {r['n_hosts_x_tools']} | {r['med_ratio_R3_over_R2w']} {r['ci_R3']} | "
              f"{r['person_share_pi']} {r['ci_pi']} | {r['med_ratio_R4_over_R2w']} {r['ci_R4']} | "
              f"{r['med_ratio_R3m_over_R2w']} {r['ci_R3m']} |")
v = json.load(open(R / "verdict.json"))
md += ["\n**Registered verdict**\n", f"verdict: **{v['verdict']}**; passing bands: {v['passing_bands']}", "",
       "| band | K1 AUC [CI] | history d [CI] (below cut-off) | R3m/R2w | K5 AUC | collapse | passes |", "|---|---|---|---|---|---|---|"]
for b, x in v["per_band"].items():
    md.append(f"| {b} | {x['K1_auc']:.3f} {x['K1_ci']} | {x['history_d']} {x['history_ci']} ({x['history_below_cutoff']}) | "
              f"{x['R3m_ratio']} | {x['K5_auc']} | {x['collapse']} | {x['passes']} |")
(R / "tables.md").write_text("\n".join(md) + "\n")
print("wrote", R / "tables.md")
